let currentLang = "sq";

function setLanguage(lang) {
  lang = lang === "en" ? "en" : "sq";
  currentLang = lang;
  try {
    localStorage.setItem("arbenl_lang", lang);
  } catch {}

  document
    .getElementById("btn-lang-sq")
    .classList.toggle("active", lang === "sq");
  document
    .getElementById("btn-lang-en")
    .classList.toggle("active", lang === "en");
  document.documentElement.lang = lang;

  const dict = translations[lang] || translations.sq;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });
}

function setView(viewName, updateHash = true) {
  const studentPanel = document.getElementById("view-student");
  const profilePanel = document.getElementById("view-profile");
  const studentSubnav = document.getElementById("student-subnav");
  const btnStudent = document.getElementById("btn-view-student");
  const btnProfile = document.getElementById("btn-view-profile");

  if (viewName === "profile") {
    studentPanel.classList.remove("active");
    profilePanel.classList.add("active");
    studentSubnav.style.display = "none";
    btnStudent.classList.remove("active");
    btnProfile.classList.add("active");
    btnStudent.setAttribute("aria-selected", "false");
    btnProfile.setAttribute("aria-selected", "true");
    if (updateHash) history.replaceState(null, null, "#profile");
  } else {
    profilePanel.classList.remove("active");
    studentPanel.classList.add("active");
    studentSubnav.style.display = "block";
    btnProfile.classList.remove("active");
    btnStudent.classList.add("active");
    btnProfile.setAttribute("aria-selected", "false");
    btnStudent.setAttribute("aria-selected", "true");
    if (updateHash) history.replaceState(null, null, "#student");
  }
}

function mobileNavJump(viewName, elementSelector) {
  setView(viewName, false);
  history.replaceState(null, "", elementSelector);
  setTimeout(() => {
    const target = document.querySelector(elementSelector);
    if (target) {
      target.scrollIntoView({ behavior: "smooth" });
    }
  }, 50);

  document
    .querySelectorAll(".mobile-tab-btn")
    .forEach((btn) => btn.classList.remove("active"));
  const activeBtn = Array.from(
    document.querySelectorAll(".mobile-tab-btn"),
  ).find((b) => b.dataset.jump === elementSelector);
  if (activeBtn) activeBtn.classList.add("active");
}

function toggleWeek(cardId) {
  const card = document.getElementById(cardId);
  if (card) {
    card.classList.toggle("expanded");
    card
      .querySelector(".week-header")
      .setAttribute(
        "aria-expanded",
        String(card.classList.contains("expanded")),
      );
  }
}

async function copyCommand(btn, text) {
  const originalText = btn.textContent;
  try {
    await navigator.clipboard.writeText(text);
    btn.textContent = "✓ " + (currentLang === "sq" ? "Kopjuar!" : "Copied!");
    btn.classList.add("copied");
    setTimeout(() => {
      btn.textContent = originalText;
      btn.classList.remove("copied");
    }, 2000);
  } catch {
    btn.textContent =
      currentLang === "sq" ? "Kopjo tekstin manualisht" : "Copy text manually";
    setTimeout(() => {
      btn.textContent = originalText;
    }, 4000);
  }
}

window.addEventListener("DOMContentLoaded", () => {
  document
    .querySelectorAll("[data-view]")
    .forEach((el) =>
      el.addEventListener("click", () => setView(el.dataset.view)),
    );
  document
    .querySelectorAll("[data-language]")
    .forEach((el) =>
      el.addEventListener("click", () => setLanguage(el.dataset.language)),
    );
  document
    .querySelectorAll("[data-week]")
    .forEach((el) =>
      el.addEventListener("click", () => toggleWeek(el.dataset.week)),
    );
  document
    .querySelectorAll("[data-copy]")
    .forEach((el) =>
      el.addEventListener("click", () => copyCommand(el, el.dataset.copy)),
    );
  document
    .querySelectorAll("[data-jump]")
    .forEach((el) =>
      el.addEventListener("click", () =>
        mobileNavJump("student", el.dataset.jump),
      ),
    );

  document.querySelectorAll(".week-header").forEach((header) => {
    header.setAttribute("role", "button");
    header.tabIndex = 0;
    header.setAttribute(
      "aria-expanded",
      String(header.closest(".week-card").classList.contains("expanded")),
    );
    header.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") {
        e.preventDefault();
        header.click();
      }
    });
  });
  document.getElementById("open-week").addEventListener("click", () => {
    const card = document.getElementById(
      document.getElementById("week-jump").value,
    );
    card.classList.add("expanded");
    card.querySelector(".week-header").setAttribute("aria-expanded", "true");
    history.replaceState(null, "", "#" + card.id);
    card.scrollIntoView({ behavior: "smooth" });
    card.querySelector(".week-header").focus({ preventScroll: true });
  });
  let savedLang = "sq";
  try {
    savedLang = localStorage.getItem("arbenl_lang") || "sq";
  } catch {}
  setLanguage(savedLang);
  if (/^#week-\d+$/.test(window.location.hash)) {
    const linkedWeek = document.getElementById(window.location.hash.slice(1));
    if (linkedWeek) {
      linkedWeek.classList.add("expanded");
      linkedWeek
        .querySelector(".week-header")
        .setAttribute("aria-expanded", "true");
    }
  }

  if (window.location.hash === "#profile") {
    setView("profile", false);
  } else {
    setView("student", false);
  }
});
